// Shared PDF template for MomCare reports (client-side, jsPDF + autotable).
// A4 portrait, built-in Helvetica only. Every report uses the same pieces:
// header band, metadata block, summary boxes, bar charts, section
// headings, tables, notes, and the footer on every page.

import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import {
  COLORS,
  CONTENT,
  EMPTY_LINE,
  FOOTER_LEFT,
  PAGE,
  barLengths,
  boxRow,
  manilaDateTime,
  pageLabel,
  type Rgb,
} from '@/lib/report-layout';

export interface ReportMeta {
  title: string;
  /** e.g. "Oct 1, 2026 - Oct 31, 2026" or "As of Oct 19, 2026". */
  period: string;
  generatedBy: string;
  /** Lines such as "Period: this month". */
  filters?: string[];
  generatedAt?: Date;
  /** An extra footer line on every page, e.g. "Prepared for clinical use by …". */
  footerNote?: string;
  /** A first meta line in dark bold, e.g. the facility's name and place. */
  facility?: string;
  /** A highlighted line under the meta block, e.g. "Internal draft, not an official submission". */
  notice?: string;
}

export interface SummaryItem {
  label: string;
  value: string | number;
}

export interface BarItem {
  label: string;
  value: number;
  color?: Rgb;
}

export interface TableSpec {
  head: string[];
  rows: (string | number)[][];
  /** Column indexes to right-align (numbers). */
  numeric?: number[];
  /** Relative column widths, optional. */
  widths?: number[];
}

/** Loads /momcare-logo.png as a data URL; null if it can't be loaded. */
async function loadLogo(): Promise<string | null> {
  try {
    const res = await fetch('/momcare-logo.png');
    if (!res.ok) return null;
    const blob = await res.blob();
    // Scaled down to the size it is printed at (18 mm), so the logo
    // doesn't make every report a megabyte.
    const bitmap = await createImageBitmap(blob);
    const canvas = document.createElement('canvas');
    canvas.width = 144;
    canvas.height = 144;
    const ctx = canvas.getContext('2d');
    if (!ctx) return null;
    ctx.drawImage(bitmap, 0, 0, canvas.width, canvas.height);
    return canvas.toDataURL('image/png');
  } catch {
    return null;
  }
}

export class ReportPdf {
  readonly doc: jsPDF;
  private y: number = CONTENT.top;
  private constructor(private readonly meta: ReportMeta, private readonly logo: string | null) {
    this.doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' });
    this.doc.setFont('helvetica', 'normal');
    this.doc.setProperties({ title: `MomCare - ${meta.title}`, creator: 'MomCare dashboard' });
    this.drawHeader();
    this.drawMeta();
  }

  static async create(meta: ReportMeta): Promise<ReportPdf> {
    return new ReportPdf(meta, await loadLogo());
  }

  private color(kind: 'fill' | 'draw' | 'text', rgb: Rgb) {
    if (kind === 'fill') this.doc.setFillColor(rgb[0], rgb[1], rgb[2]);
    else if (kind === 'draw') this.doc.setDrawColor(rgb[0], rgb[1], rgb[2]);
    else this.doc.setTextColor(rgb[0], rgb[1], rgb[2]);
  }

  /** Header band on the current page. */
  private drawHeader() {
    const d = this.doc;
    this.color('fill', COLORS.headerFill);
    d.rect(0, 0, PAGE.width, PAGE.headerHeight, 'F');
    this.color('fill', COLORS.primary);
    d.rect(0, PAGE.headerHeight - 1.2, PAGE.width, 1.2, 'F');
    let x = CONTENT.left;
    if (this.logo) {
      d.addImage(this.logo, 'PNG', x, 6, 18, 18);
      x += 22;
    }
    this.color('text', COLORS.primary);
    d.setFont('helvetica', 'bold');
    d.setFontSize(10);
    d.text('MomCare', x, 11);
    this.color('text', COLORS.ink);
    d.setFontSize(15);
    d.text(d.splitTextToSize(this.meta.title, CONTENT.right - x)[0], x, 18);
    d.setFont('helvetica', 'normal');
    d.setFontSize(9.5);
    this.color('text', COLORS.muted);
    d.text(d.splitTextToSize(this.meta.period, CONTENT.right - x)[0], x, 24);
  }

  private drawMeta() {
    const d = this.doc;
    if (this.meta.facility) {
      d.setFont('helvetica', 'bold');
      d.setFontSize(10);
      this.color('text', COLORS.ink);
      d.text(d.splitTextToSize(this.meta.facility, CONTENT.width)[0], CONTENT.left, this.y);
      d.setFont('helvetica', 'normal');
      this.y += 5;
    }
    const lines = [
      `Generated by ${this.meta.generatedBy}`,
      `Generated on ${manilaDateTime(this.meta.generatedAt ?? new Date())} (Manila time)`,
      ...(this.meta.filters ?? []),
    ];
    d.setFontSize(8.5);
    this.color('text', COLORS.muted);
    for (const line of lines) {
      for (const part of d.splitTextToSize(line, CONTENT.width)) {
        d.text(part, CONTENT.left, this.y);
        this.y += 4.2;
      }
    }
    if (this.meta.notice) {
      d.setFont('helvetica', 'bold');
      d.setFontSize(9);
      this.color('text', COLORS.pending);
      d.text(d.splitTextToSize(this.meta.notice, CONTENT.width)[0], CONTENT.left, this.y + 0.5);
      d.setFont('helvetica', 'normal');
      this.y += 5;
    }
    this.y += 3;
  }

  /** Starts a new page when fewer than `needed` mm remain. */
  ensureSpace(needed: number) {
    if (this.y + needed <= CONTENT.bottom) return;
    this.doc.addPage();
    this.drawHeader();
    this.y = CONTENT.top;
  }

  heading(text: string) {
    this.ensureSpace(16);
    const d = this.doc;
    this.y += 3;
    d.setFont('helvetica', 'bold');
    d.setFontSize(11.5);
    this.color('text', COLORS.ink);
    d.text(text, CONTENT.left, this.y);
    this.color('draw', COLORS.rule);
    d.setLineWidth(0.3);
    d.line(CONTENT.left, this.y + 1.8, CONTENT.right, this.y + 1.8);
    d.setFont('helvetica', 'normal');
    this.y += 7;
  }

  /** 3 to 4 key numbers in boxes across the page. */
  summary(items: SummaryItem[]) {
    const height = 19;
    this.ensureSpace(height + 4);
    const d = this.doc;
    const { width, xs } = boxRow(items.length, CONTENT.width, 4);
    items.forEach((item, i) => {
      const x = CONTENT.left + xs[i];
      this.color('draw', COLORS.rule);
      this.color('fill', [255, 255, 255]);
      d.setLineWidth(0.3);
      d.roundedRect(x, this.y, width, height, 2, 2, 'FD');
      this.color('fill', COLORS.chart[i % COLORS.chart.length]);
      d.rect(x, this.y + 3, 1.2, height - 6, 'F');
      d.setFont('helvetica', 'bold');
      d.setFontSize(15);
      this.color('text', COLORS.ink);
      d.text(String(item.value), x + 5, this.y + 9);
      d.setFont('helvetica', 'normal');
      d.setFontSize(8);
      this.color('text', COLORS.muted);
      d.text(d.splitTextToSize(item.label, width - 7).slice(0, 2), x + 5, this.y + 14);
    });
    this.y += height + 6;
  }

  /** Horizontal bar chart drawn with jsPDF primitives. */
  barChart(items: BarItem[]) {
    if (items.length === 0 || items.every((i) => i.value === 0)) {
      this.empty();
      return;
    }
    const d = this.doc;
    const labelWidth = 48;
    const valueWidth = 14;
    const barMax = CONTENT.width - labelWidth - valueWidth - 4;
    const lengths = barLengths(items.map((i) => i.value), barMax);
    const rowH = 7;
    items.forEach((item, i) => {
      this.ensureSpace(rowH + 1);
      d.setFontSize(8.5);
      this.color('text', COLORS.ink);
      const label = d.splitTextToSize(item.label, labelWidth - 2)[0] as string;
      d.text(label, CONTENT.left, this.y + 4.6);
      this.color('fill', COLORS.zebra);
      d.rect(CONTENT.left + labelWidth, this.y + 1, barMax, 5, 'F');
      this.color('fill', item.color ?? COLORS.chart[i % COLORS.chart.length]);
      if (lengths[i] > 0) d.rect(CONTENT.left + labelWidth, this.y + 1, lengths[i], 5, 'F');
      this.color('text', COLORS.ink);
      d.text(String(item.value), CONTENT.right, this.y + 4.6, { align: 'right' });
      this.y += rowH;
    });
    this.y += 4;
  }

  /** Table with a header row repeated on every page, zebra rows,
   *  right-aligned numbers, wrapped long text and no row split. */
  table(spec: TableSpec) {
    if (spec.rows.length === 0) {
      this.empty();
      return;
    }
    this.ensureSpace(16);
    const total = spec.widths?.reduce((a, b) => a + b, 0) ?? 0;
    const columnStyles: Record<number, { halign?: 'right'; cellWidth?: number }> = {};
    spec.head.forEach((_, i) => {
      columnStyles[i] = {};
      if (spec.numeric?.includes(i)) columnStyles[i].halign = 'right';
      if (spec.widths && total > 0) columnStyles[i].cellWidth = (spec.widths[i] / total) * CONTENT.width;
    });
    autoTable(this.doc, {
      head: [spec.head],
      body: spec.rows.map((r) => r.map((c) => String(c))),
      startY: this.y,
      margin: { left: CONTENT.left, right: PAGE.width - CONTENT.right, top: CONTENT.top, bottom: PAGE.height - CONTENT.bottom },
      theme: 'plain',
      showHead: 'everyPage',
      rowPageBreak: 'avoid',
      styles: { font: 'helvetica', fontSize: 8.5, cellPadding: 1.8, overflow: 'linebreak', textColor: COLORS.ink as unknown as [number, number, number], lineColor: COLORS.rule as unknown as [number, number, number] },
      headStyles: { fontStyle: 'bold', fillColor: COLORS.headerFill as unknown as [number, number, number], textColor: COLORS.ink as unknown as [number, number, number] },
      alternateRowStyles: { fillColor: COLORS.zebra as unknown as [number, number, number] },
      columnStyles,
      didParseCell: (data) => {
        if (data.section === 'head' && spec.numeric?.includes(data.column.index)) data.cell.styles.halign = 'right';
      },
      // A table that continues on a new page gets the header band too.
      didDrawPage: (data) => {
        if (data.pageNumber > 1) this.drawHeader();
      },
    });
    this.y = ((this.doc as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? this.y) + 6;
  }

  /** Label / value pairs in two columns (e.g. a profile). */
  keyValues(pairs: { label: string; value: string }[]) {
    const d = this.doc;
    const colWidth = (CONTENT.width - 6) / 2;
    const labelWidth = 30;
    const rows = Math.ceil(pairs.length / 2);
    for (let r = 0; r < rows; r++) {
      const cells = [pairs[r], pairs[r + rows]].filter(Boolean);
      const heights = cells.map((c) => (d.splitTextToSize(c.value, colWidth - labelWidth) as string[]).length);
      const h = Math.max(1, ...heights) * 4.2 + 2.2;
      this.ensureSpace(h);
      cells.forEach((c, i) => {
        const x = CONTENT.left + i * (colWidth + 6);
        d.setFontSize(8.5);
        this.color('text', COLORS.muted);
        d.text(c.label, x, this.y + 3.5);
        this.color('text', COLORS.ink);
        d.text(d.splitTextToSize(c.value, colWidth - labelWidth) as string[], x + labelWidth, this.y + 3.5);
      });
      this.color('draw', COLORS.rule);
      d.setLineWidth(0.2);
      d.line(CONTENT.left, this.y + h - 0.6, CONTENT.right, this.y + h - 0.6);
      this.y += h;
    }
    this.y += 4;
  }

  /** A small line chart drawn with jsPDF primitives: one or more series
   *  over the same x positions (e.g. one point per Snapshot). */
  lineChart(input: {
    xLabels: string[];
    series: { label: string; values: (number | null)[]; color: Rgb }[];
    unit?: string;
  }) {
    const all = input.series.flatMap((s) => s.values.filter((v): v is number => v !== null));
    if (all.length === 0) {
      this.empty();
      return;
    }
    const d = this.doc;
    const height = 46;
    this.ensureSpace(height + 10);
    const left = CONTENT.left + 12;
    const right = CONTENT.right - 2;
    const top = this.y + 2;
    const bottom = this.y + height - 8;
    const lo = Math.min(...all);
    const hi = Math.max(...all);
    const pad = hi === lo ? Math.max(1, Math.abs(hi) * 0.05) : (hi - lo) * 0.1;
    const min = Math.floor(lo - pad);
    const max = Math.ceil(hi + pad);
    const n = Math.max(1, input.xLabels.length - 1);
    const xAt = (i: number) => (input.xLabels.length === 1 ? (left + right) / 2 : left + (i / n) * (right - left));
    const yAt = (v: number) => bottom - ((v - min) / (max - min)) * (bottom - top);

    // Axes, gridlines and labels.
    d.setLineWidth(0.2);
    this.color('draw', COLORS.rule);
    d.setFontSize(7);
    this.color('text', COLORS.muted);
    for (const v of [min, (min + max) / 2, max]) {
      d.line(left, yAt(v), right, yAt(v));
      // The middle tick can be a half (36.5): show it, not a rounded twin of an end tick.
      d.text(Number.isInteger(v) ? String(v) : v.toFixed(1), left - 2, yAt(v) + 1, { align: 'right' });
    }
    const step = Math.max(1, Math.ceil(input.xLabels.length / 6));
    input.xLabels.forEach((l, i) => {
      if (i % step === 0 || i === input.xLabels.length - 1) d.text(l, xAt(i), bottom + 4, { align: 'center' });
    });

    // Series: lines between recorded points, a dot at each point.
    for (const s of input.series) {
      this.color('draw', s.color);
      this.color('fill', s.color);
      d.setLineWidth(0.6);
      let prev: { x: number; y: number } | null = null;
      s.values.forEach((v, i) => {
        if (v === null) return;
        const p = { x: xAt(i), y: yAt(v) };
        if (prev) d.line(prev.x, prev.y, p.x, p.y);
        d.circle(p.x, p.y, 0.7, 'F');
        prev = p;
      });
    }

    // Legend.
    let lx = left;
    d.setFontSize(7.5);
    for (const s of input.series) {
      this.color('fill', s.color);
      d.rect(lx, bottom + 6.5, 3, 1.6, 'F');
      this.color('text', COLORS.ink);
      const label = input.unit ? `${s.label} (${input.unit})` : s.label;
      d.text(label, lx + 4, bottom + 8);
      lx += d.getTextWidth(label) + 10;
    }
    this.y += height + 4;
  }

  /** Vertical bars, one per item in order (e.g. one per day), with the
   *  top value on the axis and about eight x labels. */
  columnChart(items: BarItem[]) {
    if (items.length === 0 || items.every((i) => i.value === 0)) {
      this.empty();
      return;
    }
    const d = this.doc;
    const height = 50;
    this.ensureSpace(height + 4);
    const left = CONTENT.left + 10;
    const right = CONTENT.right;
    const top = this.y + 4;
    const bottom = this.y + height - 8;
    const max = Math.max(...items.map((i) => i.value));
    const lengths = barLengths(items.map((i) => i.value), bottom - top);
    const slot = (right - left) / items.length;
    const bar = Math.max(0.6, Math.min(slot * 0.7, 12));

    d.setLineWidth(0.2);
    this.color('draw', COLORS.rule);
    d.setFontSize(7);
    this.color('text', COLORS.muted);
    for (const v of [0, max]) {
      const y = bottom - (v / max) * (bottom - top);
      d.line(left, y, right, y);
      d.text(String(v), left - 2, y + 1, { align: 'right' });
    }

    const step = Math.max(1, Math.ceil(items.length / 8));
    items.forEach((item, i) => {
      const x = left + i * slot + (slot - bar) / 2;
      this.color('fill', item.color ?? COLORS.primary);
      if (lengths[i] > 0) d.rect(x, bottom - lengths[i], bar, lengths[i], 'F');
      if (i % step === 0) {
        this.color('text', COLORS.muted);
        d.text(item.label, x + bar / 2, bottom + 4, { align: 'center' });
      }
    });
    this.y += height;
  }

  note(text: string) {
    const d = this.doc;
    d.setFontSize(8.5);
    const lines = d.splitTextToSize(text, CONTENT.width) as string[];
    this.ensureSpace(lines.length * 4.2 + 2);
    this.color('text', COLORS.muted);
    for (const line of lines) {
      d.text(line, CONTENT.left, this.y);
      this.y += 4.2;
    }
    this.y += 2;
  }

  /** Signature lines side by side, e.g. "Prepared by" and "Reviewed by". */
  signatures(labels: string[]) {
    const d = this.doc;
    this.ensureSpace(26);
    this.y += 14;
    const { width, xs } = boxRow(labels.length, CONTENT.width, 12);
    this.color('draw', COLORS.ink);
    d.setLineWidth(0.3);
    d.setFontSize(8.5);
    this.color('text', COLORS.muted);
    labels.forEach((label, i) => {
      const x = CONTENT.left + xs[i];
      d.line(x, this.y, x + width, this.y);
      d.text(d.splitTextToSize(label, width)[0], x, this.y + 4.5);
    });
    this.y += 10;
  }

  empty() {
    this.ensureSpace(8);
    this.doc.setFont('helvetica', 'italic');
    this.doc.setFontSize(9);
    this.color('text', COLORS.muted);
    this.doc.text(EMPTY_LINE, CONTENT.left, this.y + 3);
    this.doc.setFont('helvetica', 'normal');
    this.y += 9;
  }

  /**
   * Adds a first page in A4 landscape drawn by `draw` (no header band), in
   * front of the report's portrait pages. Call it once, after the portrait
   * content: the document's default stays portrait, so page breaks inside
   * tables never turn landscape.
   */
  coverSheet(draw: (doc: jsPDF, logo: string | null) => void) {
    const d = this.doc;
    d.addPage('a4', 'l');
    draw(d, this.logo);
    d.movePage(d.getNumberOfPages(), 1);
    d.setPage(d.getNumberOfPages());
  }

  /** Footer on every page (sized to that page), then the finished file. */
  finish(): Blob {
    const d = this.doc;
    const pages = d.getNumberOfPages();
    for (let p = 1; p <= pages; p++) {
      d.setPage(p);
      const w = d.internal.pageSize.getWidth();
      const h = d.internal.pageSize.getHeight();
      const right = w - PAGE.margin;
      this.color('draw', COLORS.rule);
      d.setLineWidth(0.3);
      d.line(CONTENT.left, h - PAGE.footerHeight, right, h - PAGE.footerHeight);
      d.setFontSize(8);
      this.color('text', COLORS.muted);
      d.text(FOOTER_LEFT, CONTENT.left, h - PAGE.footerHeight + 5);
      if (this.meta.footerNote) {
        d.text(d.splitTextToSize(this.meta.footerNote, right - CONTENT.left)[0], CONTENT.left, h - PAGE.footerHeight + 9);
      }
      d.text(pageLabel(p, pages), right, h - PAGE.footerHeight + 5, { align: 'right' });
    }
    return d.output('blob');
  }

  /** Builds the file and hands it to the browser as a download. */
  save(fileName: string) {
    const url = URL.createObjectURL(this.finish());
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 10_000);
  }
}
