// Shared PDF template for MomCare reports (client-side, jsPDF + autotable).
// A4 portrait, built-in Helvetica only. Every report uses the same pieces:
// header band, metadata block, summary boxes, bar charts, section
// headings, tables, notes, and the footer on every page.

import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import {
  COLORS,
  CONTENT,
  EMPTY_LINE,
  FOOTER_LEFT,
  PAGE,
  barLengths,
  boxRow,
  manilaDateTime,
  pageLabel,
  type Rgb,
} from '@/lib/report-layout';

export interface ReportMeta {
  title: string;
  /** e.g. "Oct 1, 2026 - Oct 31, 2026" or "As of Oct 19, 2026". */
  period: string;
  generatedBy: string;
  /** Lines such as "Period: this month". */
  filters?: string[];
  generatedAt?: Date;
}

export interface SummaryItem {
  label: string;
  value: string | number;
}

export interface BarItem {
  label: string;
  value: number;
  color?: Rgb;
}

export interface TableSpec {
  head: string[];
  rows: (string | number)[][];
  /** Column indexes to right-align (numbers). */
  numeric?: number[];
  /** Relative column widths, optional. */
  widths?: number[];
}

/** Loads /momcare-logo.png as a data URL; null if it can't be loaded. */
async function loadLogo(): Promise<string | null> {
  try {
    const res = await fetch('/momcare-logo.png');
    if (!res.ok) return null;
    const blob = await res.blob();
    return await new Promise<string>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(String(reader.result));
      reader.onerror = () => reject(reader.error);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

export class ReportPdf {
  readonly doc: jsPDF;
  private y: number = CONTENT.top;
  private constructor(private readonly meta: ReportMeta, private readonly logo: string | null) {
    this.doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' });
    this.doc.setFont('helvetica', 'normal');
    this.doc.setProperties({ title: `MomCare - ${meta.title}`, creator: 'MomCare dashboard' });
    this.drawHeader();
    this.drawMeta();
  }

  static async create(meta: ReportMeta): Promise<ReportPdf> {
    return new ReportPdf(meta, await loadLogo());
  }

  private color(kind: 'fill' | 'draw' | 'text', rgb: Rgb) {
    if (kind === 'fill') this.doc.setFillColor(rgb[0], rgb[1], rgb[2]);
    else if (kind === 'draw') this.doc.setDrawColor(rgb[0], rgb[1], rgb[2]);
    else this.doc.setTextColor(rgb[0], rgb[1], rgb[2]);
  }

  /** Header band on the current page. */
  private drawHeader() {
    const d = this.doc;
    this.color('fill', COLORS.headerFill);
    d.rect(0, 0, PAGE.width, PAGE.headerHeight, 'F');
    this.color('fill', COLORS.primary);
    d.rect(0, PAGE.headerHeight - 1.2, PAGE.width, 1.2, 'F');
    let x = CONTENT.left;
    if (this.logo) {
      d.addImage(this.logo, 'PNG', x, 6, 18, 18);
      x += 22;
    }
    this.color('text', COLORS.primary);
    d.setFont('helvetica', 'bold');
    d.setFontSize(10);
    d.text('MomCare', x, 11);
    this.color('text', COLORS.ink);
    d.setFontSize(15);
    d.text(d.splitTextToSize(this.meta.title, CONTENT.right - x)[0], x, 18);
    d.setFont('helvetica', 'normal');
    d.setFontSize(9.5);
    this.color('text', COLORS.muted);
    d.text(d.splitTextToSize(this.meta.period, CONTENT.right - x)[0], x, 24);
  }

  private drawMeta() {
    const d = this.doc;
    const lines = [
      `Generated by ${this.meta.generatedBy}`,
      `Generated on ${manilaDateTime(this.meta.generatedAt ?? new Date())} (Manila time)`,
      ...(this.meta.filters ?? []),
    ];
    d.setFontSize(8.5);
    this.color('text', COLORS.muted);
    for (const line of lines) {
      for (const part of d.splitTextToSize(line, CONTENT.width)) {
        d.text(part, CONTENT.left, this.y);
        this.y += 4.2;
      }
    }
    this.y += 3;
  }

  /** Starts a new page when fewer than `needed` mm remain. */
  ensureSpace(needed: number) {
    if (this.y + needed <= CONTENT.bottom) return;
    this.doc.addPage();
    this.drawHeader();
    this.y = CONTENT.top;
  }

  heading(text: string) {
    this.ensureSpace(16);
    const d = this.doc;
    this.y += 3;
    d.setFont('helvetica', 'bold');
    d.setFontSize(11.5);
    this.color('text', COLORS.ink);
    d.text(text, CONTENT.left, this.y);
    this.color('draw', COLORS.rule);
    d.setLineWidth(0.3);
    d.line(CONTENT.left, this.y + 1.8, CONTENT.right, this.y + 1.8);
    d.setFont('helvetica', 'normal');
    this.y += 7;
  }

  /** 3 to 4 key numbers in boxes across the page. */
  summary(items: SummaryItem[]) {
    const height = 19;
    this.ensureSpace(height + 4);
    const d = this.doc;
    const { width, xs } = boxRow(items.length, CONTENT.width, 4);
    items.forEach((item, i) => {
      const x = CONTENT.left + xs[i];
      this.color('draw', COLORS.rule);
      this.color('fill', [255, 255, 255]);
      d.setLineWidth(0.3);
      d.roundedRect(x, this.y, width, height, 2, 2, 'FD');
      this.color('fill', COLORS.chart[i % COLORS.chart.length]);
      d.rect(x, this.y + 3, 1.2, height - 6, 'F');
      d.setFont('helvetica', 'bold');
      d.setFontSize(15);
      this.color('text', COLORS.ink);
      d.text(String(item.value), x + 5, this.y + 9);
      d.setFont('helvetica', 'normal');
      d.setFontSize(8);
      this.color('text', COLORS.muted);
      d.text(d.splitTextToSize(item.label, width - 7).slice(0, 2), x + 5, this.y + 14);
    });
    this.y += height + 6;
  }

  /** Horizontal bar chart drawn with jsPDF primitives. */
  barChart(items: BarItem[]) {
    if (items.length === 0 || items.every((i) => i.value === 0)) {
      this.empty();
      return;
    }
    const d = this.doc;
    const labelWidth = 48;
    const valueWidth = 14;
    const barMax = CONTENT.width - labelWidth - valueWidth - 4;
    const lengths = barLengths(items.map((i) => i.value), barMax);
    const rowH = 7;
    items.forEach((item, i) => {
      this.ensureSpace(rowH + 1);
      d.setFontSize(8.5);
      this.color('text', COLORS.ink);
      const label = d.splitTextToSize(item.label, labelWidth - 2)[0] as string;
      d.text(label, CONTENT.left, this.y + 4.6);
      this.color('fill', COLORS.zebra);
      d.rect(CONTENT.left + labelWidth, this.y + 1, barMax, 5, 'F');
      this.color('fill', item.color ?? COLORS.chart[i % COLORS.chart.length]);
      if (lengths[i] > 0) d.rect(CONTENT.left + labelWidth, this.y + 1, lengths[i], 5, 'F');
      this.color('text', COLORS.ink);
      d.text(String(item.value), CONTENT.right, this.y + 4.6, { align: 'right' });
      this.y += rowH;
    });
    this.y += 4;
  }

  /** Table with a header row repeated on every page, zebra rows,
   *  right-aligned numbers, wrapped long text and no row split. */
  table(spec: TableSpec) {
    if (spec.rows.length === 0) {
      this.empty();
      return;
    }
    this.ensureSpace(16);
    const total = spec.widths?.reduce((a, b) => a + b, 0) ?? 0;
    const columnStyles: Record<number, { halign?: 'right'; cellWidth?: number }> = {};
    spec.head.forEach((_, i) => {
      columnStyles[i] = {};
      if (spec.numeric?.includes(i)) columnStyles[i].halign = 'right';
      if (spec.widths && total > 0) columnStyles[i].cellWidth = (spec.widths[i] / total) * CONTENT.width;
    });
    autoTable(this.doc, {
      head: [spec.head],
      body: spec.rows.map((r) => r.map((c) => String(c))),
      startY: this.y,
      margin: { left: CONTENT.left, right: PAGE.width - CONTENT.right, top: CONTENT.top, bottom: PAGE.height - CONTENT.bottom },
      theme: 'plain',
      showHead: 'everyPage',
      rowPageBreak: 'avoid',
      styles: { font: 'helvetica', fontSize: 8.5, cellPadding: 1.8, overflow: 'linebreak', textColor: COLORS.ink as unknown as [number, number, number], lineColor: COLORS.rule as unknown as [number, number, number] },
      headStyles: { fontStyle: 'bold', fillColor: COLORS.headerFill as unknown as [number, number, number], textColor: COLORS.ink as unknown as [number, number, number] },
      alternateRowStyles: { fillColor: COLORS.zebra as unknown as [number, number, number] },
      columnStyles,
      didParseCell: (data) => {
        if (data.section === 'head' && spec.numeric?.includes(data.column.index)) data.cell.styles.halign = 'right';
      },
      // A table that continues on a new page gets the header band too.
      didDrawPage: (data) => {
        if (data.pageNumber > 1) this.drawHeader();
      },
    });
    this.y = ((this.doc as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? this.y) + 6;
  }

  note(text: string) {
    const d = this.doc;
    d.setFontSize(8.5);
    const lines = d.splitTextToSize(text, CONTENT.width) as string[];
    this.ensureSpace(lines.length * 4.2 + 2);
    this.color('text', COLORS.muted);
    for (const line of lines) {
      d.text(line, CONTENT.left, this.y);
      this.y += 4.2;
    }
    this.y += 2;
  }

  empty() {
    this.ensureSpace(8);
    this.doc.setFont('helvetica', 'italic');
    this.doc.setFontSize(9);
    this.color('text', COLORS.muted);
    this.doc.text(EMPTY_LINE, CONTENT.left, this.y + 3);
    this.doc.setFont('helvetica', 'normal');
    this.y += 9;
  }

  /** Footer on every page, then the finished file. */
  finish(): Blob {
    const d = this.doc;
    const pages = d.getNumberOfPages();
    for (let p = 1; p <= pages; p++) {
      d.setPage(p);
      this.color('draw', COLORS.rule);
      d.setLineWidth(0.3);
      d.line(CONTENT.left, PAGE.height - PAGE.footerHeight, CONTENT.right, PAGE.height - PAGE.footerHeight);
      d.setFontSize(8);
      this.color('text', COLORS.muted);
      d.text(FOOTER_LEFT, CONTENT.left, PAGE.height - PAGE.footerHeight + 5);
      d.text(pageLabel(p, pages), CONTENT.right, PAGE.height - PAGE.footerHeight + 5, { align: 'right' });
    }
    return d.output('blob');
  }

  /** Builds the file and hands it to the browser as a download. */
  save(fileName: string) {
    const url = URL.createObjectURL(this.finish());
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 10_000);
  }
}
