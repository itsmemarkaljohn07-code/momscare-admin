// Lays out the monthly Prenatal Services report (data from
// /api/admin/reports/prenatal) with the shared PDF template. Client-side.
// An internal draft for the clinic: patient names are not printed.

import type { jsPDF } from 'jspdf';
import { ReportPdf } from '@/lib/report-pdf';
import { manilaDateKey, manilaDateTime, pdfFileName } from '@/lib/report-layout';
import { prenatalCsvRows } from '@/lib/prenatal-report-csv';
import {
  DRAFT_LABEL, GESTATION_BANDS, NOT_RECORDED, TRIMESTER_NOTE, UNDER_8, type PrenatalReport,
} from '@/lib/prenatal-report';
import { CENSUS_NOTE, STAYS_RECORDED_FROM, STAYS_SCOPE_NOTE } from '@/lib/stay-report';

/** "2026-09" -> "September 2026". */
export function monthLabel(month: string): string {
  const d = new Date(`${month}-01T00:00:00Z`);
  return Number.isNaN(d.getTime()) ? month : d.toLocaleDateString('en-US', { timeZone: 'UTC', month: 'long', year: 'numeric' });
}

const trimesterOf = (label: string) =>
  label === UNDER_8 ? '1st' : label === NOT_RECORDED ? '-' : (['1st', '2nd', '3rd'][(GESTATION_BANDS.find((b) => b.label === label)?.trimester ?? 1) - 1]);

const GROUP_ROWS = new Set(['I. ADMISSIONS', 'II. DELIVERIES', 'III. TRANSFER TO CDH', 'PRENATAL CHECK UP']);

/**
 * Page 1: the clinic's paper monthly report on A4 landscape, black and
 * white. The grid rows, weekday marks and bottom totals are the CSV's rows
 * (prenatalCsvRows), so the two files always show the same cells.
 */
function drawClinicSheet(d: jsPDF, r: PrenatalReport, logo: string | null) {
  const W = d.internal.pageSize.getWidth();
  const M = 10;
  const csv = prenatalCsvRows(r);
  const at = (label: string) => csv.findIndex((row) => row[0] === label);
  const head = csv[at('ITEM')];
  const weekday = csv[at('DAY')];
  const gridEnd = csv.findIndex((row, i) => i > at('DAY') && (row[0] === 'Note' || row[0] === 'TOTAL OF DELIVERIES'));
  const body = csv.slice(at('DAY') + 1, gridEnd);
  const days = head.length - 2;
  const cell = (v: string | number | undefined) => (v === undefined ? '' : String(v));

  d.setTextColor(0, 0, 0);
  d.setDrawColor(0, 0, 0);
  if (logo) d.addImage(logo, 'PNG', M, 8, 11, 11);

  // Header, centred like the paper.
  let y = 12;
  const centre = (text: string, size: number, bold = false) => {
    d.setFont('helvetica', bold ? 'bold' : 'normal');
    d.setFontSize(size);
    d.text(text, W / 2, y, { align: 'center' });
    y += size * 0.45;
  };
  centre(r.facility.name.toUpperCase(), 10, true);
  centre(r.facility.location.toUpperCase(), 9.5, true);
  centre('MONTHLY REPORT', 9.5, true);
  centre(monthLabel(r.month), 9.5);
  d.setTextColor(90, 90, 90);
  centre(`${DRAFT_LABEL} - Generated by MomCare ${manilaDateTime(new Date(r.generatedAt))} (Manila time)`, 7);
  d.setTextColor(0, 0, 0);

  // The grid: label column, one column per day, TOTAL.
  const labelW = 38;
  const totalW = 14;
  const dayW = (W - 2 * M - labelW - totalW) / days;
  const rowH = 6.4;
  const headH = 9;
  const top = y + 2;
  const xs = (i: number) => M + labelW + i * dayW;
  d.setFillColor(232, 232, 232);
  d.rect(M, top, W - 2 * M, headH, 'F');

  d.setFont('helvetica', 'bold');
  d.setFontSize(7);
  d.text('ITEM', M + 1.5, top + 5.6);
  for (let i = 0; i < days; i++) {
    const cx = xs(i) + dayW / 2;
    d.setFont('helvetica', 'bold');
    d.setFontSize(7);
    d.text(cell(head[i + 1]), cx, top + 3.8, { align: 'center' });
    if (weekday[i + 1]) {
      d.setFont('helvetica', 'normal');
      d.setFontSize(5.5);
      d.text(cell(weekday[i + 1]), cx, top + 7.6, { align: 'center' });
    }
  }
  d.setFont('helvetica', 'bold');
  d.setFontSize(7);
  d.text('TOTAL', W - M - totalW / 2, top + 5.6, { align: 'center' });

  body.forEach((row, ri) => {
    const ty = top + headH + ri * rowH;
    const bold = GROUP_ROWS.has(cell(row[0]));
    d.setFont('helvetica', bold ? 'bold' : 'normal');
    d.setFontSize(6.8);
    d.text(cell(row[0]), M + (bold ? 1.5 : 4), ty + 4.3);
    for (let i = 0; i < days; i++) {
      const v = cell(row[i + 1]);
      if (v) d.text(v, xs(i) + dayW / 2, ty + 4.3, { align: 'center' });
    }
    const total = cell(row[days + 1]);
    d.setFontSize(total.length > 4 ? 5.4 : 6.8);
    d.text(total, W - M - totalW / 2, ty + 4.3, { align: 'center' });
  });

  // Grid lines, thin and black like the paper.
  const bottom = top + headH + body.length * rowH;
  d.setLineWidth(0.15);
  d.rect(M, top, W - 2 * M, bottom - top);
  for (let i = 0; i <= days; i++) d.line(xs(i), top, xs(i), bottom);
  for (let ri = 0; ri <= body.length; ri++) d.line(M, top + headH + ri * rowH, W - M, top + headH + ri * rowH);

  // Below the grid: totals bottom left, signatures bottom right.
  let by = bottom + 8;
  d.setFontSize(8.5);
  for (const label of ['TOTAL OF DELIVERIES', 'MALE', 'FEMALE']) {
    const row = csv[at(label)];
    d.setFont('helvetica', 'bold');
    d.text(`${label}:`, M, by);
    d.setFont('helvetica', 'normal');
    d.text(cell(row?.[1]), M + 40, by);
    by += 5;
  }
  if (r.stays) {
    d.setFontSize(6.5);
    d.setTextColor(90, 90, 90);
    d.text(`${STAYS_SCOPE_NOTE} CENSUS uses a provisional definition (see the notes on the next pages).`, M, by + 1);
    d.setTextColor(0, 0, 0);
  }
  const sx = W - M - 85;
  d.setFontSize(8.5);
  d.setFont('helvetica', 'bold');
  d.text('PREPARED BY:', sx, bottom + 8);
  d.setLineWidth(0.3);
  d.line(sx + 25, bottom + 18, W - M, bottom + 18);
  d.text('HEAD OF FACILITY', sx + 25 + (W - M - sx - 25) / 2, bottom + 22, { align: 'center' });
  d.setFont('helvetica', 'normal');
}

export async function downloadPrenatalReport(input: { report: PrenatalReport; generatedBy: string }): Promise<void> {
  const { report: r, generatedBy } = input;
  const now = new Date(r.generatedAt);
  const pdf = await ReportPdf.create({
    title: 'Prenatal Services Report',
    period: monthLabel(r.month),
    facility: `${r.facility.name}, ${r.facility.location}`,
    notice: DRAFT_LABEL,
    generatedBy,
    generatedAt: now,
  });

  const t = r.totals;
  const notRecordedIdx = r.ageColumns.length - 1;
  pdf.heading('Summary');
  pdf.summary([
    { label: 'Prenatal check-ups (visits)', value: t.visits },
    { label: 'Patients seen (unique)', value: t.uniquePatients },
    { label: 'Visits, age not recorded', value: t.visitsByAge[notRecordedIdx] },
    { label: 'Visits, due date not recorded', value: r.dataQuality.visitsWithoutDueDate },
  ]);

  pdf.note("Page 1 is the clinic's monthly sheet with the daily counts for every row.");
  pdf.note('A visit is a completed "Prenatal Checkup" appointment on that date. Age is in full years on the visit date; "Age not recorded" means the patient has no date of birth in MomCare. Total = all age columns.');

  pdf.heading('Patients seen by age group');
  pdf.table({
    head: ['Age group', 'Visits', 'Unique patients'],
    rows: [...r.ageColumns.map((c, i) => [c, t.visitsByAge[i], t.uniqueByAge[i]]), ['Total', t.visits, t.uniquePatients]],
    numeric: [1, 2],
  });
  pdf.note('Each patient is counted once, in the age group of her first visit of the month.');

  pdf.heading('Visits by gestational age at the visit');
  pdf.table({
    head: ['Weeks', 'Trimester', 'Visits'],
    rows: r.gestation.map((g) => [g.label === UNDER_8 ? 'Under 8' : g.label === NOT_RECORDED ? 'Due date not recorded' : g.label, trimesterOf(g.label), g.visits]),
    numeric: [2],
  });
  pdf.note(TRIMESTER_NOTE);

  // Stay rows (from birth stays), or "Not recorded" before they were kept;
  // the daily counts are on page 1.
  pdf.heading('Admissions, deliveries and discharges');
  const st = r.stays;
  if (st) {
    pdf.summary([
      { label: 'Total of deliveries', value: st.rows.deliveries.total },
      { label: 'Male', value: st.rows.liveMale.total },
      { label: 'Female', value: st.rows.liveFemale.total },
      { label: 'Stillbirths', value: st.rows.stillbirths.total },
    ]);
    pdf.note(`${STAYS_SCOPE_NOTE} Admissions on the clinic sheet = mother + newborn; discharges = mother + baby. Twins are one delivery with two newborns; a transfer never adds a delivery.`);
    pdf.note(CENSUS_NOTE);
  } else {
    pdf.note(`Not recorded: birth stays are kept in MomCare only from ${monthLabel(STAYS_RECORDED_FROM)}.`);
  }

  pdf.heading('Other rows of the monthly report');
  pdf.table({ head: ['Row', 'Value'], rows: r.noSourceRows.map((row) => [row, NOT_RECORDED]) });
  pdf.note('MomCare has no record for these rows, so they are left as "Not recorded" rather than 0.');

  const q = r.dataQuality;
  pdf.heading('Data quality');
  pdf.table({
    head: ['Check', 'Count'],
    rows: [
      ['Visits by patients without a date of birth (age not recorded)', q.visitsWithoutDob],
      ['Patients without a date of birth', q.patientsWithoutDob.length],
      ['Visits by patients without a due date (gestation not recorded)', q.visitsWithoutDueDate],
      ['Completed visits not approved by the doctor (counted)', q.visitsNotApproved],
      ['"Other" appointments in the month (not counted; check them)', q.otherAppointments],
      ['Prenatal appointments still upcoming (not counted)', q.notCompleted.upcoming],
      ['Prenatal appointments missed (not counted)', q.notCompleted.missed],
      ['Prenatal appointments cancelled (not counted)', q.notCompleted.cancelled],
      ['Stays without a discharge date (counted present to month end)', st ? st.withoutDischarge.length : NOT_RECORDED],
      ['Stays without a delivery recorded', st ? st.withoutOutcome.length : NOT_RECORDED],
    ],
    numeric: [1],
  });

  pdf.coverSheet((doc, logo) => drawClinicSheet(doc, r, logo));

  pdf.save(pdfFileName(`prenatal-services-${r.month}`, manilaDateKey(now)));
}
