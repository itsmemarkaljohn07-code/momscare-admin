// The List of Pregnant Women as an A4 landscape PDF laid out like the
// clinic's paper list: grouped headers (trimesters, postnatal check-ups),
// a bordered table that repeats its header on every page, names wrapped
// rather than clipped. Client-side.

import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import { COLORS, FOOTER_LEFT, PAGE, manilaDateKey, manilaDateTime, pageLabel, pdfFileName } from '@/lib/report-layout';
import { FACILITY, GESTATION_BANDS } from '@/lib/prenatal-report';
import { POSTNATAL_COLUMNS, LIST_DRAFT, LIST_SCOPE_NOTE, LIST_TITLE, LIST_TRIMESTER_NOTE, rowCells, type PregnantList } from '@/lib/pregnant-list';
import { EMPTY_LIST_NOTE } from '@/lib/pregnant-list-csv';

function longDate(day: string): string {
  const d = new Date(`${day}T00:00:00Z`);
  return d.toLocaleDateString('en-US', { timeZone: 'UTC', month: 'long', day: 'numeric', year: 'numeric' });
}

export function downloadPregnantList(input: { list: PregnantList; generatedAt: string }): void {
  const { list } = input;
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'landscape' });
  doc.setProperties({ title: `MomCare - List of Pregnant Women ${list.reportDate}`, creator: 'MomCare dashboard' });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 10;

  // Header, centred like the paper.
  let y = 13;
  const centre = (text: string, size: number, bold: boolean, gap: number, rgb: [number, number, number] = [0, 0, 0]) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    doc.setTextColor(rgb[0], rgb[1], rgb[2]);
    doc.text(text, W / 2, y, { align: 'center' });
    y += gap;
  };
  centre(FACILITY.name.toUpperCase(), 12, true, 5.5);
  centre(FACILITY.location.toUpperCase(), 10.5, true, 5);
  centre(LIST_TITLE, 10.5, true, 5);
  centre(`Report date: ${longDate(list.reportDate)}  ·  ${list.barangay ? `Barangay: ${list.barangay}` : 'All barangays'}`, 9, false, 4.5);
  centre(LIST_DRAFT, 8, true, 3.8, COLORS.pending as unknown as [number, number, number]);
  centre(`${LIST_SCOPE_NOTE} Generated by MomCare ${manilaDateTime(new Date(input.generatedAt))} (Manila time)`, 7, false, 0, [110, 110, 110]);

  const cell = { halign: 'center' as const, valign: 'middle' as const };
  const head = [
    [
      { content: 'No.', rowSpan: 2, styles: cell },
      { content: 'Last name', rowSpan: 2, styles: { valign: 'middle' as const } },
      { content: 'First name', rowSpan: 2, styles: { valign: 'middle' as const } },
      { content: 'Middle name', rowSpan: 2, styles: { valign: 'middle' as const } },
      { content: 'Age', rowSpan: 2, styles: cell },
      { content: 'Address', rowSpan: 2, styles: { valign: 'middle' as const } },
      { content: 'Age of gestation', rowSpan: 2, styles: cell },
      { content: 'Trimester', rowSpan: 2, styles: cell },
      { content: 'Gravida', rowSpan: 2, styles: cell },
      { content: 'Para', rowSpan: 2, styles: cell },
      { content: '1st tri', colSpan: 1, styles: cell },
      { content: '2nd tri', colSpan: 2, styles: cell },
      { content: '3rd tri', colSpan: 5, styles: cell },
      { content: 'Mother and Child Postnatal Check-ups', colSpan: 4, styles: cell },
    ],
    [...GESTATION_BANDS.map((b) => ({ content: b.label, styles: cell })), ...POSTNATAL_COLUMNS.map((c) => ({ content: c, styles: cell }))],
  ];
  const body = list.rows.length
    ? list.rows.map((r) => rowCells(r).map(String))
    : [[{ content: EMPTY_LIST_NOTE, colSpan: 22, styles: { halign: 'center' as const, fontStyle: 'italic' as const } }]];

  // Widths (mm) for 277 mm: names and address wrap, ticks stay narrow.
  const widths = [8, 20, 20, 17, 9, 28, 14, 15, 12, 12, 9, 9, 9, 9, 9, 8, 8, 9, 14, 12, 12, 14];
  autoTable(doc, {
    head,
    body,
    startY: y + 4,
    margin: { left: M, right: M, top: 14, bottom: PAGE.footerHeight + 6 },
    theme: 'grid',
    showHead: 'everyPage',
    rowPageBreak: 'avoid',
    styles: { font: 'helvetica', fontSize: 7, cellPadding: 1.2, overflow: 'linebreak', textColor: [0, 0, 0], lineColor: [0, 0, 0], lineWidth: 0.2, minCellHeight: 6.4 },
    headStyles: { fillColor: [229, 231, 235], textColor: [0, 0, 0], fontStyle: 'bold', fontSize: 7 },
    columnStyles: Object.fromEntries(widths.map((w, i) => [i, { cellWidth: w, halign: i === 0 || i === 4 || i >= 6 ? 'center' : 'left' }])),
    didParseCell: (d) => {
      // "Not recorded" stays readable but quiet.
      if (d.section === 'body' && d.cell.raw === 'Not recorded') { d.cell.styles.textColor = [110, 110, 110]; d.cell.styles.fontSize = 6; }
    },
  });

  // The trimester rule, under the table (on a new page if it does not fit).
  const tableEnd = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
  let noteY = tableEnd + 5;
  if (noteY > H - PAGE.footerHeight - 4) {
    doc.addPage();
    noteY = 18;
  }
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(60, 60, 60);
  doc.text(`${LIST_TRIMESTER_NOTE}.`, M, noteY);

  // Footer on every page.
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setDrawColor(COLORS.rule[0], COLORS.rule[1], COLORS.rule[2]);
    doc.setLineWidth(0.3);
    doc.line(M, H - PAGE.footerHeight, W - M, H - PAGE.footerHeight);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(COLORS.muted[0], COLORS.muted[1], COLORS.muted[2]);
    doc.text(FOOTER_LEFT, M, H - PAGE.footerHeight + 5);
    doc.text(pageLabel(p, pages), W - M, H - PAGE.footerHeight + 5, { align: 'right' });
  }
  doc.save(pdfFileName(`list-of-pregnant-women-${list.reportDate}`, manilaDateKey(new Date(input.generatedAt))));
}
